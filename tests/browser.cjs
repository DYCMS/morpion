const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage();
  const errors = [], external = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', req => { if (/^https?:/.test(req.url())) external.push(req.url()); });
  await page.goto(process.env.MORPION_URL || require('node:url').pathToFileURL(require('node:path').join(__dirname,'../index.html')).href);
  const cells = page.locator('.cell');
  const status = () => page.locator('#status').textContent();
  const reset = () => page.locator('#restart').click();
  const play = async sequence => { for (const index of sequence) await cells.nth(index).click(); };
  assert.equal(await cells.count(),9);
  assert.equal(await status(),'Au tour de X — Joueur 1');
  await play([0,1]);
  assert.equal(await cells.nth(0).textContent(),'X');
  assert.equal(await cells.nth(1).textContent(),'O');
  assert.equal(await status(),'Au tour de X — Joueur 1');
  console.log('1. Ouverture locale, grille vide et alternance : OK');
  await cells.nth(0).evaluate(button => button.click());
  assert.equal(await cells.nth(0).textContent(),'X');
  assert.equal(await status(),'Au tour de X — Joueur 1');
  console.log('2. Case occupée refusée sans changer le tour : OK');
  const wins = [[0,3,1,4,2],[3,0,4,1,5],[6,0,7,1,8],[0,1,3,2,6],[1,0,4,2,7],[2,0,5,1,8],[0,1,4,2,8],[2,0,4,1,6],[3,0,4,1,8,2]];
  for (const sequence of wins) {
    await reset(); await play(sequence);
    assert.match(await status(),new RegExp('^'+(sequence.length%2?'X':'O')+' a gagné'));
    assert.equal(await page.locator('.winner').count(),3);
    assert.equal(await page.locator('.cell:disabled').count(),9);
    const before = await cells.allTextContents();
    await cells.evaluateAll(buttons => buttons.forEach(b => b.click()));
    assert.deepEqual(await cells.allTextContents(),before);
  }
  console.log('3. Huit alignements, victoire de X/O et blocage après victoire : OK');
  await reset(); await play([0,1,2,4,3,5,7,6,8]);
  assert.match(await status(),/^Match nul/);
  assert.equal(await page.locator('.cell:disabled').count(),9);
  console.log('4. Grille pleine sans gagnant : match nul et blocage : OK');
  await reset();
  assert.deepEqual(await cells.allTextContents(),Array(9).fill(''));
  assert.equal(await page.locator('.cell:enabled').count(),9);
  await page.keyboard.press('Enter');
  assert.equal(await cells.nth(0).textContent(),'X');
  await reset();
  await page.setViewportSize({width:375,height:812});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true);

  // Les cinq séquences exactes de l’annexe, avec les cases numérotées de 1 à 9.
  await reset();
  await cells.nth(0).click();
  await cells.nth(0).evaluate(button => button.click());
  await cells.nth(3).click();
  assert.deepEqual(await cells.allTextContents(),['X','','','O','','','','','']);
  assert.equal(await status(),'Au tour de X — Joueur 1');
  console.log('Annexe 1 — Tour et case occupée : réussi dans Chromium');
  await reset(); await play([0,3,1,4,2]);
  assert.equal(await status(),'X a gagné ! — Joueur 1');
  console.log('Annexe 2 — Victoire de X : réussi dans Chromium');
  const afterWin=await cells.allTextContents();
  await cells.nth(8).evaluate(button => button.click());
  assert.deepEqual(await cells.allTextContents(),afterWin);
  console.log('Annexe 3 — Partie terminée : réussi dans Chromium');
  await reset(); assert.deepEqual(await cells.allTextContents(),Array(9).fill(''));
  await cells.nth(8).click();assert.equal(await cells.nth(8).textContent(),'X');
  console.log('Annexe 4 — Recommencer : réussi dans Chromium');
  await reset();await play([0,1,2,4,3,5,7,6,8]);
  assert.match(await status(),/^Match nul/);
  console.log('Annexe 5 — Match nul : réussi dans Chromium');
  assert.deepEqual(errors,[]);
  if (!process.env.MORPION_URL) assert.deepEqual(external,[]);
  console.log('5. Recommencer, clavier, affichage mobile et aucune ressource externe : OK');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
